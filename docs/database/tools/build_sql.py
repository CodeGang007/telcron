"""
Generate PostgreSQL DDL from docs/database/schema_spec.py.

    python3 docs/database/tools/build_sql.py

Writes (generated — do not edit by hand):
  db/migrations/20261114120000_extensions_and_types.sql   extensions + all enum types
  db/migrations/20261114120200_phase1_schema.sql          core tables, constraints, FKs, indexes, triggers
  db/schema-next/phase2_schema.sql                        AI-engine tables (not yet applied)
  db/schema-next/phase3_schema.sql                        engagement tables (not yet applied)

Hand-written companions (rules the spec cannot express declaratively):
  db/migrations/20261114120100_helpers.sql, db/migrations/20261114120300_phase1_rules.sql,
  db/schema-next/phase2_rules.sql, db/schema-next/phase3_rules.sql
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]          # Codebase/
sys.path.insert(0, str(ROOT / "docs" / "database"))
import schema_spec as S  # noqa: E402

HEADER = "-- GENERATED by docs/database/tools/build_sql.py from schema_spec.py — do not edit by hand.\n"


def ident(*parts, suffix):
    base = "_".join(p for p in parts if p)
    name = f"{base}_{suffix}"
    if len(name) <= 63:
        return name
    h = hashlib.md5(name.encode()).hexdigest()[:6]
    return f"{base[:63 - len(suffix) - 8]}_{h}_{suffix}"


def cols_of(expr):
    return [c.strip() for c in expr.split(",")]


def col_def(c, t):
    s = f"    {c.name} {c.type}"
    if c.generated:
        s += f" GENERATED ALWAYS AS ({c.generated}) STORED"
    if c.nn or c.name in S.pk_cols(t):
        s += " NOT NULL"
    if c.default and not c.generated:
        s += f" DEFAULT {c.default}"
    return s


def table_ddl(t):
    lines = [col_def(c, t) for c in t.cols]
    pk = S.pk_cols(t)
    if t.partition_by:
        pk = pk + [t.partition_by] if t.partition_by not in pk else pk
    lines.append(f"    CONSTRAINT {ident(t.name, suffix='pkey')} PRIMARY KEY ({', '.join(pk)})")
    for c in t.cols:
        if c.uk:
            lines.append(f"    CONSTRAINT {ident(t.name, c.name, suffix='key')} UNIQUE ({c.name})")
    for u in t.uniques:
        if u.is_constraint():
            nnd = "NULLS NOT DISTINCT " if u.nulls_not_distinct else ""
            lines.append(f"    CONSTRAINT {ident(t.name, *cols_of(u.cols), suffix='key')} UNIQUE {nnd}({u.cols})")
    for i, chk in enumerate(t.checks, 1):
        lines.append(f"    CONSTRAINT {ident(t.name, suffix=f'chk{i}')} CHECK ({chk})")
    tail = f" PARTITION BY RANGE ({t.partition_by})" if t.partition_by else ""
    out = [f"CREATE TABLE {t.name} (\n" + ",\n".join(lines) + f"\n){tail};"]
    out.append(f"COMMENT ON TABLE {t.name} IS {sql_str(t.purpose)};")
    for c in t.cols:
        if c.note:
            out.append(f"COMMENT ON COLUMN {t.name}.{c.name} IS {sql_str(c.note)};")
    return out


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def index_ddl(t):
    out, leading = [], set()
    pk = S.pk_cols(t)
    leading.add(pk[0])
    for c in t.cols:
        if c.uk:
            leading.add(c.name)
    for n, u in enumerate(t.uniques, 1):
        first = re.split(r"[ ,(]", u.cols.strip())[0]
        leading.add(first)
        if not u.is_constraint():
            nnd = " NULLS NOT DISTINCT" if u.nulls_not_distinct else ""
            where = f" WHERE {u.where}" if u.where else ""
            out.append(f"CREATE UNIQUE INDEX {ident(t.name, f'u{n}', suffix='uidx')} ON {t.name} ({u.cols}){nnd}{where};")
    for n, ix in enumerate(t.indexes, 1):
        first = re.split(r"[ ,(]", ix.cols.strip())[0]
        if not ix.where and not ix.using:
            leading.add(first)
        using = f" USING {ix.using}" if ix.using else ""
        where = f" WHERE {ix.where}" if ix.where else ""
        out.append(f"CREATE INDEX {ident(t.name, f'i{n}', suffix='idx')} ON {t.name}{using} ({ix.cols}){where};")
    return out, leading


def fk_phase(child, parent):
    return max(S.TABLE_BY_NAME[child].phase, S.TABLE_BY_NAME[parent].phase)


def fk_statements(phase):
    """FK constraints (+ covering indexes) whose both endpoints exist by `phase` and which belong to it."""
    out = []
    for t in S.TABLES:
        composite_firsts = {cols_of(f.cols)[0]: f for f in t.fks}
        _, leading = index_ddl(t)
        for c in t.cols:
            if not c.fk:
                continue
            pt, pc = c.fk.split(".")
            fk = composite_firsts.get(c.name)
            if fk and fk.ref.split("(")[0] == pt:
                continue  # emitted as composite below
            if fk_phase(t.name, pt) != phase:
                continue
            od = {"restrict": "RESTRICT", "cascade": "CASCADE", "set null": "SET NULL"}[c.on_delete]
            out.append(f"ALTER TABLE {t.name} ADD CONSTRAINT {ident(t.name, c.name, suffix='fkey')} "
                       f"FOREIGN KEY ({c.name}) REFERENCES {pt} ({pc}) ON DELETE {od};")
            if c.name not in leading:
                out.append(f"CREATE INDEX {ident(t.name, c.name, suffix='fk_idx')} ON {t.name} ({c.name});")
                leading.add(c.name)
        for f in t.fks:
            pt = f.ref.split("(")[0].strip()
            if fk_phase(t.name, pt) != phase:
                continue
            cols = cols_of(f.cols)
            od = {"restrict": "RESTRICT", "cascade": "CASCADE", "set null": "SET NULL"}[f.on_delete]
            defer = " DEFERRABLE INITIALLY DEFERRED" if f.deferrable else ""
            out.append(f"ALTER TABLE {t.name} ADD CONSTRAINT {ident(t.name, *cols, suffix='fkey')} "
                       f"FOREIGN KEY ({f.cols}) REFERENCES {f.ref} ON DELETE {od}{defer};")
            if cols[0] not in leading:
                out.append(f"CREATE INDEX {ident(t.name, cols[0], suffix='fk_idx')} ON {t.name} ({f.cols});")
                leading.add(cols[0])
    return out


def trigger_statements(t):
    out = []
    names = [c.name for c in t.cols]
    if "updated_at" in names:
        out.append(f"CREATE TRIGGER {t.name}_set_updated_at BEFORE UPDATE ON {t.name} "
                   f"FOR EACH ROW EXECUTE FUNCTION telcron_set_updated_at();")
    if t.immutable is not None:
        args = ", ".join(sql_str(c) for c in t.immutable)
        out.append(f"CREATE TRIGGER {t.name}_guard_immutable BEFORE UPDATE OR DELETE ON {t.name} "
                   f"FOR EACH ROW EXECUTE FUNCTION telcron_guard_immutable({args});")
    if t.partition_by:
        out.append(f"SELECT telcron_create_monthly_partitions('{t.name}', date_trunc('month', now())::date, 4);")
    return out


def phase_sql(phase):
    tables = [t for t in S.TABLES if t.phase == phase]
    body = [HEADER]
    for t in tables:
        body += [f"\n-- ── {t.name} ({S.DOMAINS[t.domain][0]}) ──"] + table_ddl(t)
    body.append("\n-- ── indexes ──")
    for t in tables:
        body += index_ddl(t)[0]
    body.append("\n-- ── foreign keys (+ covering indexes) ──")
    body += fk_statements(phase)
    body.append("\n-- ── triggers & partitions ──")
    for t in tables:
        body += trigger_statements(t)
    return "\n".join(body) + "\n", tables


def types_sql():
    out = [HEADER, "-- migrate:up"]
    out += [f"CREATE EXTENSION IF NOT EXISTS {e};" for e in S.EXTENSIONS]
    for name, vals in S.ENUMS.items():
        out.append(f"CREATE TYPE {name} AS ENUM ({', '.join(sql_str(v) for v in vals)});")
    out.append("\n-- migrate:down")
    out += [f"DROP TYPE IF EXISTS {n};" for n in reversed(S.ENUMS)]
    out.append("-- extensions are left installed")
    return "\n".join(out) + "\n"


def main():
    errs = S.validate()
    if errs:
        raise SystemExit("\n".join(errs))
    mig = ROOT / "db" / "migrations"
    nxt = ROOT / "db" / "schema-next"
    mig.mkdir(parents=True, exist_ok=True)
    nxt.mkdir(parents=True, exist_ok=True)
    (mig / "20261114120000_extensions_and_types.sql").write_text(types_sql())

    sql, tables = phase_sql(1)
    down = "\n".join(f"DROP TABLE IF EXISTS {t.name} CASCADE;" for t in reversed(tables))
    (mig / "20261114120200_phase1_schema.sql").write_text(
        "-- migrate:up\n" + sql + "\n-- migrate:down\n" + down + "\n")
    for p in (2, 3):
        sql, _ = phase_sql(p)
        (nxt / f"phase{p}_schema.sql").write_text(sql)
    print("Wrote migrations and schema-next files")


if __name__ == "__main__":
    main()
